CREATE OR REPLACE TABLE ?score_mbr_nec_ipi_tbl as (
with NECESSITY_MERCH_HIER_PURCHASE_DATE AS (
SELECT
a.MBR_NO as GROUP_LOYALTY_MEMBER_NUMBER,
a.SYSTEMDATE,
txn.NEC_SKUPLUS3_MERCH_HIER,
txn.TRANSACTION_DATE
from 	
?src_active_mbr_base a
left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
REPLACE(sku_sub.SKUPLUS3_MERCH_HIER_DESC,' ','_') AS SKUPLUS3_MERCH_HIER,
CASE WHEN SKUPLUS3_MERCH_HIER LIKE '%VEGETABLE%' THEN 'VEGETABLES'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%MILK%' THEN 'MILK'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%SNACKS%' THEN 'SNACKS'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%DRINK%' THEN 'DRINKS'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%MEAL%' THEN 'MEALS'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%POULTRY%' THEN 'POULTRY'
	 ELSE SKUPLUS3_MERCH_HIER END AS NEC_SKUPLUS3_MERCH_HIER,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join ?src_prod_hier_tbl sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
and sku_sub.SKUPLUS3_MERCH_HIER_DESC LIKE ANY ('%VEGETABLE%','BISCUITS & COOKIES','%MILK%','CHILLED DESSERTS','%SNACKS%',
'CONFECTIONERY','CHEESE DAIRY',
'INSTORE BREAD','%DRINK%','BAKERY BOUGHT IN','PACKAGED SALADS','CEREAL',
'ICE CREAM',
'CHILLED SPREADS','EGGS','COOKING','DENTAL HEALTH',
'TOILET PAPER', 'PAPER TOWELS','%MEAL%','%POULTRY%','%PASTA%')
) txn
on a.MBR_NO = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.SYSTEMDATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.SYSTEMDATE)
GROUP BY 1,2,3,4
)
,
NECESSITY_MERCH_HIER_IPI AS (
SELECT DISTINCT 
GROUP_LOYALTY_MEMBER_NUMBER,
SYSTEMDATE,
NEC_SKUPLUS3_MERCH_HIER,
TRANSACTION_DATE,
lead(TRANSACTION_DATE, 1) over (partition by GROUP_LOYALTY_MEMBER_NUMBER, SYSTEMDATE, NEC_SKUPLUS3_MERCH_HIER order by TRANSACTION_DATE) AS Next_transaction_date,
Next_transaction_date - TRANSACTION_DATE AS ipi
FROM NECESSITY_MERCH_HIER_PURCHASE_DATE
)

SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
SYSTEMDATE,
NEC_SKUPLUS3_MERCH_HIER,
MIN(IPI) AS MIN_IPI,
AVG(IPI) AS AVG_IPI,
MEDIAN(IPI) AS MEDIAN_IPI,
MAX(IPI) AS MAX_IPI
FROM NECESSITY_MERCH_HIER_IPI 
GROUP BY 1,2,3
)