insert into ?lifestage_typ2_tbl
	(GROUP_LOYALTY_MEMBER_NUMBER,
	MBR_AGE,
	LIFESTAGE_HIGH_NAME_LABEL,
	LIFESTAGE_HIGH_NAME,
	LIFESTAGE_LOW_NAME,
	EFF_FROM_DATE,
	EFF_TO_DATE,
	ACTIVE) 
SELECT
	GROUP_LOYALTY_MEMBER_NUMBER,
	MBR_AGE,
	PRED_LABEL,
	PRED_LIFESTAGE,
	CASE WHEN MBR_AGE < 35 THEN CONCAT_WS (' ','YOUNG',PRED_LIFESTAGE)
		 WHEN MBR_AGE BETWEEN 35 AND 60 THEN CONCAT_WS (' ','MIDDLE-AGED',PRED_LIFESTAGE)
		 WHEN MBR_AGE > 60 THEN CONCAT_WS (' ','OLD',PRED_LIFESTAGE) END AS PRED_LIFESTAGE_LOW_NAME,
	SYSTEMDATE,
	date('9999-12-31'),
	1
FROM ?score_output_tbl
WHERE SYSTEMDATE = CURRENT_DATE()