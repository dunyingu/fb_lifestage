CREATE OR REPLACE TABLE ?score_mbr_agg_diff_txn_tbl AS 
(
WITH LABEL_DIFF_MERCH_HIER_AGG AS (
SELECT DISTINCT
SKU_KEY,
LABEL_DIFF_MERCH_HIER
,CASE WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%INFANT%','%BABY%','%TODDLER%') THEN 'BABY'
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%KIDS%','%CHILD%','%TEEN%','%JUNIOR%','%SCHOOL%') THEN 'CHILDREN' 
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%WOMEN%','%LADIES%','%PREGNANCY%','%SHAMPOO%','%CONDITIONER%','%STYLE/BEAUT%') THEN 'WOMEN' 
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%MEN%') THEN 'MEN' 
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%ADULT%','%MULTI_VITAMINS','%INCONTINENCE') THEN 'ADULT'
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%FAMILY%','%MULTI%','%BIRTH%','%HOMES%') THEN 'FAMILY'
	  ELSE LABEL_DIFF_MERCH_HIER END AS LABEL_DIFF_MERCH_HIER_AGG
FROM 
(SELECT DISTINCT 
SKU_KEY,
REPLACE(SKUPLUS3_MERCH_HIER_DESC,' ','_')  AS LABEL_DIFF_MERCH_HIER
FROM 
?src_prod_hier_tbl
WHERE SKUPLUS3_MERCH_HIER_DESC LIKE ANY ('%INFANT%','%BABY%','%TODDLER%','%KID%','%CHILD%','TEEN%','%JUNIOR%','%YOUNG%','%ADULT%','MEN%','%LADIES%','OLD%','%ELDER%','%SENIOR%')
union
SELECT DISTINCT 
SKU_KEY,
LABEL_DIFF_SKUPLUS32_MERCH_HIER AS LABEL_DIFF_MERCH_HIER
FROM 
?prod_hier_skuplus2_tbl
union
SELECT DISTINCT 
SKU_KEY,
LABEL_DIFF_SKUPLUS321_MERCH_HIER AS LABEL_DIFF_MERCH_HIER
FROM 
?prod_hier_skuplus1_tbl)
)
, NECESSITY_MERCH_HIER_AGG AS (
SELECT
a.MBR_NO as GROUP_LOYALTY_MEMBER_NUMBER,
a.SYSTEMDATE,
count(DISTINCT txn.TRANSACTION_IDENTIFIER) AS NEC_SKUPLUS3_MERCH_HIER_AGG_TXN_CNT,
sum(nvl(txn.TOTAL_SALES_AMOUNT,0)) AS NEC_SKUPLUS3_MERCH_HIER_AGG_SALES_AMOUNT
from 	
?src_active_mbr_base a
left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
REPLACE(sku_sub.SKUPLUS3_MERCH_HIER_DESC,' ','_') AS SKUPLUS3_MERCH_HIER,
CASE WHEN SKUPLUS3_MERCH_HIER LIKE '%VEGETABLE%' THEN 'VEGETABLES'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%MILK%' THEN 'MILK'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%SNACKS%' THEN 'SNACKS'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%DRINK%' THEN 'DRINKS'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%MEAL%' THEN 'MEALS'
	 WHEN SKUPLUS3_MERCH_HIER LIKE '%POULTRY%' THEN 'POULTRY'
	 ELSE SKUPLUS3_MERCH_HIER END AS NEC_SKUPLUS3_MERCH_HIER,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join ?src_prod_hier_tbl sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
and sku_sub.SKUPLUS3_MERCH_HIER_DESC LIKE ANY ('%VEGETABLE%','BISCUITS & COOKIES','%MILK%','CHILLED DESSERTS','%SNACKS%',
'CONFECTIONERY','CHEESE DAIRY',
'INSTORE BREAD','%DRINK%','BAKERY BOUGHT IN','PACKAGED SALADS','CEREAL',
'ICE CREAM',
'CHILLED SPREADS','EGGS','COOKING','DENTAL HEALTH',
'TOILET PAPER', 'PAPER TOWELS','%MEAL%','%POULTRY%','%PASTA%')
) txn
on a.MBR_NO = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.SYSTEMDATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.SYSTEMDATE)
group by 1,2)

SELECT
a.MBR_NO as GROUP_LOYALTY_MEMBER_NUMBER,
a.SYSTEMDATE,
c.total_txn_cnt,
c.total_txn_sales_amount,
d.NEC_SKUPLUS3_MERCH_HIER_AGG_TXN_CNT AS STAPLE_MERCH_HIER_AGG_TXN_CNT,
d.NEC_SKUPLUS3_MERCH_HIER_AGG_SALES_AMOUNT AS STAPLE_MERCH_HIER_AGG_SALES_AMOUNT,
CASE WHEN c.total_txn_cnt>0 THEN d.NEC_SKUPLUS3_MERCH_HIER_AGG_TXN_CNT/c.total_txn_cnt 
	 ELSE NULL END AS STAPLE_MERCH_HIER_AGG_TXN_FREQ,
CASE WHEN c.total_txn_sales_amount>0 THEN d.NEC_SKUPLUS3_MERCH_HIER_AGG_SALES_AMOUNT/c.total_txn_sales_amount 
     ELSE NULL END AS STAPLE_MERCH_HIER_AGG_SPEND_RATIO,
txn.LABEL_DIFF_MERCH_HIER_AGG,
count(distinct txn.TRANSACTION_IDENTIFIER) AS LABEL_DIFF_MERCH_HIER_AGG_TXN_CNT,
sum(nvl(txn.TOTAL_SALES_AMOUNT,0)) AS LABEL_DIFF_MERCH_HIER_AGG_SALES_AMOUNT,
CASE WHEN c.total_txn_cnt>0 THEN LABEL_DIFF_MERCH_HIER_AGG_TXN_CNT/c.total_txn_cnt 
	 ELSE NULL END AS LABEL_DIFF_MERCH_HIER_AGG_TXN_FREQ,
CASE WHEN c.total_txn_sales_amount>0 THEN LABEL_DIFF_MERCH_HIER_AGG_SALES_AMOUNT/c.total_txn_sales_amount 
     ELSE NULL END AS LABEL_DIFF_MERCH_HIER_AGG_SPEND_RATIO
from 	
?src_active_mbr_base a
left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
sku_sub.LABEL_DIFF_MERCH_HIER_AGG,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join LABEL_DIFF_MERCH_HIER_AGG sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
) txn
on a.MBR_NO = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.SYSTEMDATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.SYSTEMDATE)
left join ?score_mbr_txn_summ_tbl c
on a.MBR_NO = c.GROUP_LOYALTY_MEMBER_NUMBER
and a.SYSTEMDATE = c.SYSTEMDATE
left JOIN NECESSITY_MERCH_HIER_AGG d
on a.MBR_NO = d.GROUP_LOYALTY_MEMBER_NUMBER
and a.SYSTEMDATE = d.SYSTEMDATE
group by 1,2,3,4,5,6,7,8,9
)