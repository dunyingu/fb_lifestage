CREATE OR REPLACE TABLE ?train_mbr_label_tbl AS (
WITH survey_kids AS (
SELECT
p.GROUP_LOYALTY_MEMBER_NUMBER,
p.RESPONSE_DATE,
p. "'BABY'" AS BABY,
p. "'YOUNG_CHILD'" AS YOUNG_CHILD,
p. "'OLD_CHILD'" AS OLD_CHILD
FROM
(
(SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
KIDS_TYPE,
count(KIDS_TYPE) AS KIDS_TYPE_CNT
FROM 
(SELECT
distinct
GROUP_LOYALTY_MEMBER_NUMBER,
GROUP_LOYALTY_MEMBER_IDNT,
RESPONSE_DATE,
GRP_LYLTY_SRVY_QUES_KEY,
GRP_LYLTY_SRVY_QUES_IDNT,
GRP_LYLTY_SRVY_RESP_TXT AS AGE_UNDER_18_RESP,
CAST(NULLIF(REPLACE(GRP_LYLTY_SRVY_RESP_TXT,',EMPTY',''),'EMPTY') AS INT) AS AGE_UNDER_18,
CASE WHEN AGE_UNDER_18 <2 THEN 'BABY' -- aged under 2 baby
     WHEN AGE_UNDER_18 BETWEEN 2 AND 10 THEN 'YOUNG_CHILD' -- 2-10 young children
     WHEN AGE_UNDER_18 > 10 AND AGE_UNDER_18 < 18 THEN 'OLD_CHILD' END AS KIDS_TYPE, -- 10-18 older children
ROW_NUMBER () OVER (PARTITION BY GROUP_LOYALTY_MEMBER_NUMBER, RESPONSE_DATE, GRP_LYLTY_SRVY_RESP_TXT ORDER BY GRP_LYLTY_SRVY_RESP_TXT) AS rnum
FROM ?src_srvy_tbl
WHERE 
GRP_LYLTY_SRVY_QUES_IDNT = 'AGE_UNDER_18' 
AND AGE_UNDER_18 < 18)
WHERE rnum=1
GROUP BY RESPONSE_DATE,GROUP_LOYALTY_MEMBER_NUMBER, KIDS_TYPE)
	pivot (max(KIDS_TYPE_CNT) FOR KIDS_TYPE IN ('BABY','YOUNG_CHILD','OLD_CHILD')) 
) AS p
ORDER BY RESPONSE_DATE DESC, GROUP_LOYALTY_MEMBER_NUMBER
)
,
-- get the valid and clean responses to num_household_members
survey_hh_size AS (
SELECT 
DISTINCT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
GRP_LYLTY_SRVY_RESP_TXT AS NUM_HOUSEHOLD_MEMBERS_RESP,
NUM_HOUSEHOLD_MEMBERS,
CASE WHEN NUM_HOUSEHOLD_MEMBERS<5 THEN TO_VARCHAR(NUM_HOUSEHOLD_MEMBERS)
	 ELSE '5_OR_MORE' END AS HOUSEHOLD_SIZE
FROM 
(SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
GROUP_LOYALTY_MEMBER_IDNT,
RESPONSE_DATE,
GRP_LYLTY_SRVY_QUES_KEY,
GRP_LYLTY_SRVY_QUES_IDNT,
GRP_LYLTY_SRVY_RESP_TXT,
CAST ((CASE WHEN GRP_LYLTY_SRVY_RESP_TXT LIKE '%,%' THEN NULL
	 WHEN GRP_LYLTY_SRVY_RESP_TXT LIKE '99%' THEN NULL
	 WHEN upper(GRP_LYLTY_SRVY_RESP_TXT) LIKE '%EMPTY%' THEN NULL
	 WHEN upper(GRP_LYLTY_SRVY_RESP_TXT) LIKE '%MORE%' THEN 10
     WHEN GRP_LYLTY_SRVY_RESP_TXT LIKE '2%' THEN REPLACE(replace(GRP_LYLTY_SRVY_RESP_TXT, '"', ''), '''','')
     ELSE NULLIF(LTRIM(GRP_LYLTY_SRVY_RESP_TXT,'0'),'') END) AS INTEGER) AS NUM_HOUSEHOLD_MEMBERS,
ROW_NUMBER () OVER (PARTITION BY GROUP_LOYALTY_MEMBER_NUMBER, RESPONSE_DATE ORDER BY NUM_HOUSEHOLD_MEMBERS DESC) AS rnum
FROM ?src_srvy_tbl 
WHERE 
GRP_LYLTY_SRVY_QUES_IDNT = 'NUM_HOUSEHOLD_MEMBERS' 
AND NUM_HOUSEHOLD_MEMBERS <=10)
WHERE rnum = 1
ORDER BY 
RESPONSE_DATE DESC
,GROUP_LOYALTY_MEMBER_NUMBER
)
SELECT 
a.*,
b.BABY,
b.YOUNG_CHILD,
b.OLD_CHILD,
c.AGE_NUMBER AS MEMBER_AGE_NOW,
c.AGE_NUMBER - DATEDIFF('YEAR', a.RESPONSE_DATE,CURRENT_DATE()) AS MEMBER_AGE_AT_SURVEY,
c.REGISTRATION_DATE,
d.AFF_DECILE,
d.AFFLUENCE_RATING,
e.tile as RFM_TILE, 
e.RFM_SEGMENT,
CASE WHEN (b.BABY IS NOT NULL) AND (b.YOUNG_CHILD IS NULL) AND (b.OLD_CHILD IS NULL) THEN 'FAMILY_W_BABY'
	 WHEN (b.BABY IS NOT NULL) AND ((b.YOUNG_CHILD IS NOT NULL) OR (b.OLD_CHILD IS NOT NULL)) THEN 'FAMILY_W_BABY_OTHER_CHILDREN'
	 WHEN (b.BABY IS NULL) AND ((b.YOUNG_CHILD IS NOT NULL) OR (b.OLD_CHILD IS NOT NULL)) THEN 'FAMILY_W_CHILDREN'
	 -- WHEN (b.BABY IS NULL) AND (b.YOUNG_CHILD IS NOT NULL) AND (b.OLD_CHILD IS NULL) THEN 'FAMILY_W_2-10'
	 -- WHEN (b.BABY IS NULL) AND (b.YOUNG_CHILD IS NULL) AND (b.OLD_CHILD IS NOT NULL) THEN 'FAMILY_W_OLDER_CHILDREN'
	 -- WHEN (b.BABY IS NULL) AND (b.YOUNG_CHILD IS NOT NULL) AND (b.OLD_CHILD IS NOT NULL) THEN 'FAMILY_W_2-10_OLDER_CHILDREN'
	 WHEN (b.BABY IS NULL) AND (b.YOUNG_CHILD IS NULL) AND (b.OLD_CHILD IS NULL) AND a.HOUSEHOLD_SIZE = '1' THEN 'SINGLE'
	 WHEN (b.BABY IS NULL) AND (b.YOUNG_CHILD IS NULL) AND (b.OLD_CHILD IS NULL) AND a.HOUSEHOLD_SIZE = '2' THEN 'COUPLE_NO_KIDS'
	 ELSE 'MULTI-ADULT_FAMILY' END AS LIFESTAGE_LABEL	 
FROM survey_hh_size a
LEFT JOIN survey_kids b
ON a.GROUP_LOYALTY_MEMBER_NUMBER = b.GROUP_LOYALTY_MEMBER_NUMBER
AND a.RESPONSE_DATE = b.RESPONSE_DATE
INNER JOIN ?src_mbr_tbl c
ON a.GROUP_LOYALTY_MEMBER_NUMBER = c.GROUP_LOYALTY_MEMBER_NUMBER 
AND a.RESPONSE_DATE >= dateadd('month',3,c.REGISTRATION_DATE) -- 1,548,557
LEFT JOIN ?src_affluence_tbl d
ON a.GROUP_LOYALTY_MEMBER_NUMBER = d.MBR_NO
AND a.RESPONSE_DATE BETWEEN d.EFF_FROM_DATE AND d.EFF_TO_DATE
left join ?src_rfm_tbl e
ON a.GROUP_LOYALTY_MEMBER_NUMBER = e.GROUP_LOYALTY_MEMBER_NUMBER
AND a.RESPONSE_DATE BETWEEN e.EFF_FROM_DATE AND e.EFF_TO_DATE
WHERE 
a.RESPONSE_DATE >= dateadd('month',3,date('2016-12-09')) AND -- 109,1226
a.NUM_HOUSEHOLD_MEMBERS IS NOT NULL AND 
c.REGISTRATION_DATE IS NOT NULL AND 
a.NUM_HOUSEHOLD_MEMBERS >= nvl(b.BABY,0) + nvl(b.YOUNG_CHILD,0) + nvl(b.OLD_CHILD,0) + 1
)