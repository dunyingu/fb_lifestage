CREATE OR REPLACE TABLE ?train_mbr_txn_summ_tbl as (
SELECT
a.GROUP_LOYALTY_MEMBER_NUMBER,
a.RESPONSE_DATE,
a.HOUSEHOLD_SIZE,
a.MEMBER_AGE_AT_SURVEY,
a.AFF_DECILE,
a.AFFLUENCE_RATING,
a.LIFESTAGE_LABEL,
count(distinct txn.TRANSACTION_IDENTIFIER) AS total_txn_cnt,
sum(txn.TOTAL_SALES_AMOUNT) AS total_txn_sales_amount,
total_txn_sales_amount/total_txn_cnt as avg_txn_sales_amount
from
?train_mbr_label_tbl a
left join 
(SELECT
GROUP_LOYALTY_MEMBER_NUMBER,
TRANSACTION_DATE, 
TRANSACTION_IDENTIFIER,
TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl
WHERE GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL 
) txn
on a.GROUP_LOYALTY_MEMBER_NUMBER = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.RESPONSE_DATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.RESPONSE_DATE)
group by 1,2,3,4,5,6,7
)