CREATE OR REPLACE TABLE ?prod_hier_skuplus2_tbl AS (
SELECT 
DISTINCT
SKU_KEY,
SKUPLUS3_MERCH_HIER_DESC,
SKUPLUS2_MERCH_HIER_DESC,
REPLACE(REPLACE(REPLACE(SKUPLUS3_MERCH_HIER_DESC,' ','_'),'BOYS','KIDS'),'GIRLS','KIDS') AS SKUPLUS3_MERCH_HIER,
REPLACE(REPLACE(REPLACE(SKUPLUS2_MERCH_HIER_DESC,' ','_'),'BOYS','KIDS'),'GIRLS','KIDS') AS SKUPLUS2_MERCH_HIER_DESC_PROCESSED,
CASE WHEN SKUPLUS2_MERCH_HIER_DESC_PROCESSED LIKE ANY ('WOMENS','LADIES%','NAPKINS','PANTY%','TAMPONS','REUSABLES','ACCESSORIES','MENOPAUSE') THEN 'LADIES'
	 WHEN SKUPLUS2_MERCH_HIER_DESC_PROCESSED LIKE 'KIDS%' THEN 'KIDS'
	 WHEN SKUPLUS2_MERCH_HIER_DESC_PROCESSED LIKE 'TODDLER%' THEN 'BABY' 
	 WHEN SKUPLUS2_MERCH_HIER_DESC_PROCESSED LIKE ANY ('MENS%','MEN_%') THEN 'MENS' ELSE SKUPLUS2_MERCH_HIER_DESC_PROCESSED END AS SKUPLUS2_MERCH_HIER,
CONCAT_WS('-',SKUPLUS3_MERCH_HIER,SKUPLUS2_MERCH_HIER) AS LABEL_DIFF_SKUPLUS32_MERCH_HIER
FROM ?src_prod_hier_tbl
WHERE (SKUPLUS2_MERCH_HIER_DESC LIKE ANY 
('%BIRTH%','%PREGNANCY%','%INFANT%','%BABY%','%TODDLER%','%KID%','%BOY%','%GIRL%','%SCHOOL%','%CHILD%','TEEN%','%JUNIOR%','%YOUNG%','%ADULT%','MEN%','WOMENS','%LADIES%','%FAMILY%','%MULTI%','OLD%','%ELDER%','%SENIOR%','INCONTINENCE')
OR SKUPLUS3_MERCH_HIER_DESC LIKE ANY ('%SANITARY%'))
AND SKUPLUS2_MERCH_HIER_DESC NOT IN ('BABY BROCCOLI','BABY POTATOES','AGE GROUP')
AND NOT SKUPLUS3_MERCH_HIER_DESC LIKE ANY ('%BIRTH%','%PREGNANCY%','%INFANT%','%BABY%','%TODDLER%',
'%KID%','%CHILD%','TEEN%','%JUNIOR%','%YOUNG%','%SCHOOL%',
'%ADULT%','MEN%','%LADIES%','OLD%','%ELDER%','%SENIOR%','CLEANING GOODS','EASTER','FRUIT-SHELF STABLE','%JUICES%')
AND SKUPLUS1_MERCH_HIER_DESC NOT IN ('NON SCAN SALES')
)