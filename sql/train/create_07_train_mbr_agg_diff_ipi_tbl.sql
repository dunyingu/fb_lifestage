CREATE OR REPLACE TABLE ?train_mbr_agg_diff_ipi_tbl AS (
WITH LABEL_DIFF_MERCH_HIER_AGG AS (
SELECT DISTINCT
SKU_KEY,
LABEL_DIFF_MERCH_HIER
,CASE WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%INFANT%','%BABY%','%TODDLER%') THEN 'BABY'
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%KIDS%','%CHILD%','%TEEN%','%JUNIOR%','%SCHOOL%') THEN 'CHILDREN' 
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%WOMEN%','%LADIES%','%PREGNANCY%','%SHAMPOO%','%CONDITIONER%','%STYLE/BEAUT%') THEN 'WOMEN' 
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%MEN%') THEN 'MEN' 
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%ADULT%','%MULTI_VITAMINS','%INCONTINENCE') THEN 'ADULT'
	  WHEN LABEL_DIFF_MERCH_HIER LIKE ANY ('%FAMILY%','%MULTI%','%BIRTH%','%HOMES%') THEN 'FAMILY'
	  ELSE LABEL_DIFF_MERCH_HIER END AS LABEL_DIFF_MERCH_HIER_AGG
FROM 
(SELECT DISTINCT 
SKU_KEY,
REPLACE(SKUPLUS3_MERCH_HIER_DESC,' ','_')  AS LABEL_DIFF_MERCH_HIER
FROM 
?src_prod_hier_tbl
WHERE SKUPLUS3_MERCH_HIER_DESC LIKE ANY ('%INFANT%','%BABY%','%TODDLER%','%KID%','%CHILD%','TEEN%','%JUNIOR%','%YOUNG%','%ADULT%','MEN%','%LADIES%','OLD%','%ELDER%','%SENIOR%')
union
SELECT DISTINCT 
SKU_KEY,
LABEL_DIFF_SKUPLUS32_MERCH_HIER AS LABEL_DIFF_MERCH_HIER
FROM 
?prod_hier_skuplus2_tbl
union
SELECT DISTINCT 
SKU_KEY,
LABEL_DIFF_SKUPLUS321_MERCH_HIER AS LABEL_DIFF_MERCH_HIER
FROM 
?prod_hier_skuplus1_tbl)
)
,
LABEL_DIFF_MERCH_HIER_AGG_PURCHASE_DATE AS (
SELECT
a.GROUP_LOYALTY_MEMBER_NUMBER,
a.RESPONSE_DATE,
txn.LABEL_DIFF_MERCH_HIER_AGG,
txn.TRANSACTION_DATE
from 	
?train_mbr_label_tbl a
Left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
sku_sub.LABEL_DIFF_MERCH_HIER_AGG,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join LABEL_DIFF_MERCH_HIER_AGG sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
) txn
on a.GROUP_LOYALTY_MEMBER_NUMBER = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.RESPONSE_DATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.RESPONSE_DATE)
GROUP BY 1,2,3,4
)
,
LABEL_DIFF_MERCH_HIER_AGG_IPI AS (
SELECT DISTINCT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
LABEL_DIFF_MERCH_HIER_AGG,
TRANSACTION_DATE,
lead(TRANSACTION_DATE, 1) over (partition by GROUP_LOYALTY_MEMBER_NUMBER, RESPONSE_DATE, LABEL_DIFF_MERCH_HIER_AGG order by TRANSACTION_DATE) AS Next_transaction_date,
Next_transaction_date - TRANSACTION_DATE AS ipi
FROM LABEL_DIFF_MERCH_HIER_AGG_PURCHASE_DATE
)

SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
LABEL_DIFF_MERCH_HIER_AGG,
MIN(IPI) AS MIN_IPI,
AVG(IPI) AS AVG_IPI,
MEDIAN(IPI) AS MEDIAN_IPI,
MAX(IPI) AS MAX_IPI
FROM LABEL_DIFF_MERCH_HIER_AGG_IPI
GROUP BY 1,2,3
)