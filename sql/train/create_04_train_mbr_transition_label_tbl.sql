CREATE OR REPLACE TABLE ?train_mbr_transition_label_tbl AS (
WITH lifestage_transitions AS (
SELECT 
*
FROM 
(
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE AS PRIOR_RESPONSE_DATE,
LIFESTAGE_LABEL AS PRIOR_LIFESTAGE_LABEL,
round(months_between(lead(RESPONSE_DATE) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE),
				RESPONSE_DATE
			   ),1) AS MONTHS_BETWEEN_TRANSITION,
lead(MEMBER_AGE_AT_SURVEY) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE) AS MEMBER_AGE_AT_TRANSITION,
lead(RESPONSE_DATE) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE) as NEXT_RESPONSE_DATE,
lead(LIFESTAGE_LABEL) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE) as NEXT_LIFESTAGE_LABEL
FROM ?train_mbr_label_tbl
)
WHERE NEXT_LIFESTAGE_LABEL IS NOT NULL 
ORDER BY GROUP_LOYALTY_MEMBER_NUMBER,PRIOR_RESPONSE_DATE
)
,
lifestage_aug AS (
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
MEMBER_AGE_AT_SURVEY,
LIFESTAGE_LABEL
FROM 
(SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
MEMBER_AGE_AT_SURVEY,
LIFESTAGE_LABEL,
ROW_NUMBER() over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE ASC) as rnum_asc,
ROW_NUMBER() over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE DESC) as rnum_desc
FROM ?train_mbr_label_tbl -- no RESPONSE_DATE time window constraint 
-- ORDER BY GROUP_LOYALTY_MEMBER_NUMBER,RESPONSE_DATE
)
WHERE rnum_asc = 1 OR rnum_desc=1
ORDER BY GROUP_LOYALTY_MEMBER_NUMBER,RESPONSE_DATE
)
,
lifestage_aug_transitions AS (
SELECT 
*
FROM 
(
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE AS PRIOR_RESPONSE_DATE,
LIFESTAGE_LABEL AS PRIOR_LIFESTAGE_LABEL,
round(months_between(lead(RESPONSE_DATE) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE),
				RESPONSE_DATE
			   ),1) AS MONTHS_BETWEEN_TRANSITION,
lead(MEMBER_AGE_AT_SURVEY) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE) AS MEMBER_AGE_AT_TRANSITION,
lead(RESPONSE_DATE) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE) as NEXT_RESPONSE_DATE,
lead(LIFESTAGE_LABEL) over (partition by GROUP_LOYALTY_MEMBER_NUMBER order by RESPONSE_DATE) as NEXT_LIFESTAGE_LABEL  
FROM lifestage_aug
)
WHERE NEXT_LIFESTAGE_LABEL IS NOT NULL 
)

SELECT * FROM 
(SELECT * FROM lifestage_transitions)
union
(SELECT * FROM lifestage_aug_transitions)
)
