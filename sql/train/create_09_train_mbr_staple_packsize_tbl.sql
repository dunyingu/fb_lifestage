CREATE OR REPLACE TABLE ?train_mbr_staple_packsize_tbl AS (
WITH toilet_paper_txn_pack AS (
SELECT DISTINCT 
a.GROUP_LOYALTY_MEMBER_NUMBER,
a.RESPONSE_DATE,
txn.SKUPLUS3_MERCH_HIER_DESC,
txn.PACK_SIZE
from 	
?train_mbr_label_tbl a
Left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
sku_sub.SKUPLUS3_MERCH_HIER_DESC,
CAST (SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',1) AS DECIMAL(10,2)) AS PACK_SIZE,
SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',2) AS UNIT,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join ?src_prod_hier_tbl sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
AND sku_sub.SKUPLUS3_MERCH_HIER_DESC LIKE 'TOILET PAPER'
AND sku_sub.SKUPLUS2_MERCH_HIER_DESC NOT LIKE 'NON SCAN SALES'
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
) txn
on a.GROUP_LOYALTY_MEMBER_NUMBER = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.RESPONSE_DATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.RESPONSE_DATE)
)
,
pasta_txn_pack AS (
SELECT DISTINCT 
a.GROUP_LOYALTY_MEMBER_NUMBER,
a.RESPONSE_DATE,
txn.SKUPLUS3_MERCH_HIER_DESC,
txn.PACK_SIZE
from 	
?train_mbr_label_tbl a
Left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
sku_sub.SKUPLUS3_MERCH_HIER_DESC,
CAST (SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',1) AS DECIMAL(10,2)) AS PACK_SIZE_ORIGIN,
SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',2) AS UNIT,
CASE WHEN UNIT = 'KG' THEN PACK_SIZE_ORIGIN*1000
	 ELSE PACK_SIZE_ORIGIN END AS PACK_SIZE,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join ?src_prod_hier_tbl sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
AND sku_sub.SKUPLUS3_MERCH_HIER_DESC LIKE '%PASTA%'
AND sku_sub.SKUPLUS2_MERCH_HIER_DESC NOT LIKE 'NON SCAN SALES'
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
) txn
on a.GROUP_LOYALTY_MEMBER_NUMBER = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.RESPONSE_DATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.RESPONSE_DATE)
)
,
egg_txn_pack AS (
SELECT DISTINCT 
a.GROUP_LOYALTY_MEMBER_NUMBER,
a.RESPONSE_DATE,
txn.SKUPLUS3_MERCH_HIER_DESC,
txn.PACK_SIZE
from 	
?train_mbr_label_tbl a
Left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
sku_sub.SKUPLUS3_MERCH_HIER_DESC,
CAST (SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',1) AS DECIMAL(10,2)) AS PACK_SIZE_ORIGIN,
SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',2) AS UNIT,
CASE WHEN UNIT = 'KG' THEN PACK_SIZE_ORIGIN*1000
	 ELSE PACK_SIZE_ORIGIN END AS PACK_SIZE,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join ?src_prod_hier_tbl sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
AND sku_sub.SKUPLUS3_MERCH_HIER_DESC LIKE '%EGG%'
AND sku_sub.SKUPLUS2_MERCH_HIER_DESC NOT LIKE 'NON SCAN SALES'
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
) txn
on a.GROUP_LOYALTY_MEMBER_NUMBER = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.RESPONSE_DATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.RESPONSE_DATE)
)
,
milk_txn_pack AS (
SELECT DISTINCT 
a.GROUP_LOYALTY_MEMBER_NUMBER,
a.RESPONSE_DATE,
CASE WHEN txn.SKUPLUS3_MERCH_HIER_DESC LIKE '%MILK%' THEN 'MILK'
	 ELSE txn.SKUPLUS3_MERCH_HIER_DESC END AS SKUPLUS3_MERCH_HIER_DESC,
txn.PACK_SIZE
from 	
?train_mbr_label_tbl a
Left join 
(SELECT
b.GROUP_LOYALTY_MEMBER_NUMBER,
b.TRANSACTION_DATE, 
b.TRANSACTION_IDENTIFIER,
b.SKU_KEY,
sku_sub.SKUPLUS3_MERCH_HIER_DESC,
CAST (SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',1) AS DECIMAL(10,2)) AS PACK_SIZE_ORIGIN,
SPLIT_PART(sku_sub.DIFFERENTIATOR_SIZE_DESC, ' ',2) AS UNIT,
CASE WHEN UNIT = 'KG' OR UNIT = 'LITRE' THEN PACK_SIZE_ORIGIN*1000
	 ELSE PACK_SIZE_ORIGIN END AS PACK_SIZE,
b.TOTAL_SALES_AMOUNT
FROM ?src_txn_tbl b
inner join ?src_prod_hier_tbl sku_sub
on b.SKU_KEY = sku_sub.SKU_KEY
AND sku_sub.SKUPLUS3_MERCH_HIER_DESC LIKE '%MILK%'
AND sku_sub.SKUPLUS2_MERCH_HIER_DESC NOT LIKE 'NON SCAN SALES'
WHERE b.GROUP_LOYALTY_MEMBER_NUMBER IS NOT NULL
AND UNIT <> 'PACK'
) txn
on a.GROUP_LOYALTY_MEMBER_NUMBER = txn.GROUP_LOYALTY_MEMBER_NUMBER
and txn.TRANSACTION_DATE >= DATEADD('MONTH',-6,a.RESPONSE_DATE)
and txn.TRANSACTION_DATE <= DATEADD('DAY',-1,a.RESPONSE_DATE)
)

SELECT 
DISTINCT *
FROM 
(
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
SKUPLUS3_MERCH_HIER_DESC,
mode(PACK_SIZE) MODE_PACK_SIZE
FROM toilet_paper_txn_pack
GROUP BY 1,2,3
UNION
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
SKUPLUS3_MERCH_HIER_DESC,
mode(PACK_SIZE) MODE_PACK_SIZE
FROM pasta_txn_pack
GROUP BY 1,2,3
UNION
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
SKUPLUS3_MERCH_HIER_DESC,
mode(PACK_SIZE) MODE_PACK_SIZE
FROM egg_txn_pack
GROUP BY 1,2,3
UNION
SELECT 
GROUP_LOYALTY_MEMBER_NUMBER,
RESPONSE_DATE,
SKUPLUS3_MERCH_HIER_DESC,
mode(PACK_SIZE) MODE_PACK_SIZE
FROM milk_txn_pack
GROUP BY 1,2,3
)
)